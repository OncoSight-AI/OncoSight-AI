def write_reports(root, case_id, res, info, png_best, fig_path, synthetic):
    ds_dir = root / "datasets"
    man_dir = ds_dir / "manifests"
    man_dir.mkdir(parents=True, exist_ok=True)
    overall = res.overall()
    now = datetime.datetime.now().isoformat(timespec="seconds")

    # JSON (merge, do not clobber other sections)
    jpath = man_dir / "validation_report.json"
    report = {}
    if jpath.exists():
        try:
            loaded = json.loads(jpath.read_text(encoding="utf-8"))
            if isinstance(loaded, dict):
                report = loaded
        except Exception:
            shutil.copy(jpath, jpath.with_suffix(".json.bak"))
    report["nifti_3d"] = {
        "generated": now,
        "synthetic_self_test": synthetic,
        "repo_id": REPO_ID,
        "case_id": case_id,
        "overall": overall,
        "checks": res.rows,
        "geometry": info,
        "png_crosscheck": png_best,
        "figure": str(fig_path.relative_to(root)) if fig_path else None,
        "scope": "ONE case only; says nothing about the other scans",
    }
    jpath.write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")

    # Markdown
    mpath = ds_dir / "IMAGE_MASK_VALIDATION.md"
    if mpath.exists():
        old = mpath.read_text(encoding="utf-8", errors="replace")
        if MARKER not in old:
            bak = ds_dir / "IMAGE_MASK_VALIDATION.previous.md"
            if not bak.exists():
                shutil.copy(mpath, bak)
    lines = [MARKER, "", "# Image / mask validation -- 3D NIfTI pair", ""]
    if synthetic:
        lines += ["> **SYNTHETIC SELF-TEST. This is not validation of real data.**", ""]
    lines += [
        f"- Generated: {now}",
        f"- Source: `{REPO_ID}` (`images/{case_id}.nii.gz`, `masks/{case_id}.nii.gz`)",
        f"- **Overall: {overall}**",
        "",
        "**Scope:** validated ONE complete 3D NIfTI image/mask pair "
        f"(`{case_id}`). This does not establish that the other scans are valid. "
        "Geometry was read as stored; nothing was resampled or reoriented.",
        "",
        "| Check | Result | Detail |",
        "|---|---|---|",
    ]
    for r in res.rows:
        d = str(r["detail"]).replace("|", "/")
        lines.append(f"| {r['check']} | {r['status']} | {d} |")
    if fig_path:
        lines += ["", f"Figure: `{fig_path.relative_to(root)}`"]
    lines += ["", "## Geometry as stored", "", "```json", json.dumps(info, indent=2, default=str), "```", ""]
    mpath.write_text("\n".join(lines), encoding="utf-8")
    return jpath, mpath


# ----------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo-root", default=".")
    ap.add_argument("--case-id", default=DEFAULT_CASE)
    ap.add_argument("--expect-n-slices", type=int, default=None, help="n_slices from the streamed metadata row")
    ap.add_argument("--expect-spacing-z", type=float, default=None, help="spacing_z from the streamed metadata row")
    ap.add_argument("--no-png-crosscheck", action="store_true")
    ap.add_argument("--selftest", action="store_true", help="synthetic logic test, no network, writes to a temp dir")
    args = ap.parse_args()

    import nibabel as nib

    root = Path(args.repo_root).resolve()
    res = Results()
    tmp = None
    if args.selftest:
        tmp = tempfile.mkdtemp()
        root = Path(tmp) / "repo"
        root.mkdir()
        img_p, msk_p = build_synthetic(tmp)
        case_id = "SYNTHETIC"
    else:
        from huggingface_hub import hf_hub_download
        case_id = args.case_id
        raw = root / "datasets" / "raw" / "lidc_hf"
        raw.mkdir(parents=True, exist_ok=True)
        print(f"Downloading only images/{case_id}.nii.gz and masks/{case_id}.nii.gz into {raw}")
        try:
            img_p = Path(hf_hub_download(REPO_ID, f"images/{case_id}.nii.gz", repo_type="dataset", local_dir=str(raw)))
            msk_p = Path(hf_hub_download(REPO_ID, f"masks/{case_id}.nii.gz", repo_type="dataset", local_dir=str(raw)))
        except Exception as e:
            print(f"FAILED to download: {type(e).__name__}: {e}")
            sys.exit(2)
        print(f"Image file: {img_p.stat().st_size / 1e6:.1f} MB; mask file: {msk_p.stat().st_size / 1e3:.1f} kB")

    try:
        img_nii, msk_nii = nib.load(str(img_p)), nib.load(str(msk_p))
    except Exception as e:
        res.add("Load NIfTI", "FAIL", f"{type(e).__name__}: {e}")
        write_reports(root, case_id, res, {}, None, None, args.selftest)
        sys.exit(1)
    res.add("Load NIfTI", "PASS", f"{img_p.name}, {msk_p.name}")

    info, iv, mv = run_checks(img_nii, msk_nii, args.expect_n_slices, args.expect_spacing_z, res)

    png_best = None
    if iv is not None and mv is not None and (mv > 0).any() and not args.no_png_crosscheck and not args.selftest:
        png_best = crosscheck_png(case_id, iv, mv, info.get("z_axis_from_affine", 2), res)

    fig_path = None
    if iv is not None:
        vdir = root / "datasets" / "validation"
        vdir.mkdir(parents=True, exist_ok=True)
        fig_path = vdir / f"{case_id}_overview.png"
        zooms = [float(z) for z in img_nii.header.get_zooms()[:3]]
