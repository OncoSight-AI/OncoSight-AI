def make_figure(iv, mv, zooms, z_axis, out_png, title):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    def win(a, lo=-1000, hi=400):
        return np.clip((a.astype(np.float32) - lo) / (hi - lo), 0, 1)

    fg = mv > 0
    if fg.any():
        per_slice = fg.sum(axis=tuple(i for i in range(3) if i != z_axis))
        s = int(np.argmax(per_slice))
        coords = np.argwhere(fg)
        cen = np.round(coords[np.argmin(np.abs(coords[:, z_axis] - s) +
                                        0 * coords[:, 0])]).astype(int) if False else np.round(
            np.argwhere(np.take(fg, s, axis=z_axis)).mean(axis=0)).astype(int)
    else:
        s = iv.shape[z_axis] // 2
        cen = np.array([iv.shape[i] // 2 for i in range(3) if i != z_axis])
    rem = [i for i in range(3) if i != z_axis]  # in-plane axes, in array order
    a_ax, b_ax = rem
    ca, cb = int(cen[0]), int(cen[1])

    def disp(ax, arr2d, axes2d, msk2d=None, overlay=False, ttl=""):
        asp = zooms[axes2d[1]] / zooms[axes2d[0]]
        ax.imshow(win(arr2d).T, cmap="gray", origin="lower", aspect=asp, vmin=0, vmax=1)
        if msk2d is not None:
            m = np.ma.masked_where(~(msk2d.T > 0), np.ones_like(msk2d.T, dtype=float))
            ax.imshow(m, cmap="autumn", origin="lower", aspect=asp, alpha=0.55 if overlay else 1.0, vmin=0, vmax=1)
        ax.set_title(ttl, fontsize=9)
        ax.set_xticks([])
        ax.set_yticks([])

    ax_img = np.take(iv, s, axis=z_axis)
    ax_msk = np.take(mv, s, axis=z_axis)
    fig, axs = plt.subplots(2, 3, figsize=(15, 10))
    disp(axs[0, 0], ax_img, rem, None, ttl=f"CT, axis {z_axis} slice {s} (as stored)")
    axs[0, 1].imshow((ax_msk.T > 0).astype(float), cmap="gray", origin="lower",
                     aspect=zooms[b_ax] / zooms[a_ax], vmin=0, vmax=1)
    axs[0, 1].set_title("Mask (as stored)", fontsize=9)
    axs[0, 1].set_xticks([])
    axs[0, 1].set_yticks([])
    disp(axs[0, 2], ax_img, rem, ax_msk, True, "Overlay")

    h = 40
    a0, a1 = max(ca - h, 0), min(ca + h, ax_img.shape[0])
    b0, b1 = max(cb - h, 0), min(cb + h, ax_img.shape[1])
    disp(axs[1, 0], ax_img[a0:a1, b0:b1], rem, ax_msk[a0:a1, b0:b1], True, "Zoom around mask centroid")

    # views through the in-plane centroid along each in-plane axis
    sl_a = [slice(None)] * 3
    sl_a[a_ax] = ca
    sl_a[b_ax] = slice(None)
    cor_i, cor_m = iv[tuple(sl_a)], mv[tuple(sl_a)]  # dims: (b_ax, z_axis) in array order
    ord_a = sorted([b_ax, z_axis])
    disp(axs[1, 1], cor_i, ord_a, cor_m, True, f"Cut at axis {a_ax} = {ca}")
    sl_b = [slice(None)] * 3
    sl_b[b_ax] = cb
    sag_i, sag_m = iv[tuple(sl_b)], mv[tuple(sl_b)]
    ord_b = sorted([a_ax, z_axis])
    disp(axs[1, 2], sag_i, ord_b, sag_m, True, f"Cut at axis {b_ax} = {cb}")

    fig.suptitle(title + "\nPanels show array axes as stored; nothing was reoriented or resampled.", fontsize=11)
    fig.tight_layout()
    fig.savefig(out_png, dpi=110)
    plt.close(fig)


