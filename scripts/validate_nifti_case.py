# synthetic self-test data (logic test only -- NOT evidence about real data)
# ----------------------------------------------------------------------------
def build_synthetic(tmp):
    import nibabel as nib
    shape = (96, 96, 40)
    aff = np.diag([-0.7, -0.7, 2.5, 1.0])
    rng = np.random.default_rng(0)
    img = rng.normal(-800, 30, shape).astype(np.int16)
    img[:, :, :3] = 40
    msk = np.zeros(shape, np.uint8)
    xx, yy, zz = np.ogrid[:shape[0], :shape[1], :shape[2]]
    ball = (xx - 48) ** 2 + (yy - 40) ** 2 + ((zz - 20) * 3.5) ** 2 < 9 ** 2
    msk[ball] = 1
    img[ball] = 20
    img[0, 0, 0] = 1200
    i = nib.Nifti1Image(img, aff)
    i.header.set_data_dtype(np.int16)
    m = nib.Nifti1Image(msk, aff)
    m.header.set_data_dtype(np.uint8)
    i.set_qform(aff, 1)
    i.set_sform(aff, 1)
    m.set_qform(aff, 1)
    m.set_sform(aff, 1)
    ip, mp = Path(tmp) / "img.nii.gz", Path(tmp) / "msk.nii.gz"
    nib.save(i, str(ip))
    nib.save(m, str(mp))
    return ip, mp


