#!/usr/bin/env python
"""
validate_nifti_case.py -- validate ONE complete 3D image/mask NIfTI pair from
the Hugging Face dataset MedOtter/LIDC-IDRI without downloading the full 71 GB.

Repo layout (from the dataset's own file listing and README):
    images/<case_id>.nii.gz   CT in Hounsfield units, int16, native geometry
    masks/<case_id>.nii.gz    default ground truth, uint8 {0,1}
Only these two files are fetched (about 35 MB + 35 kB for the default case).

What it checks (each result is PASS / WARN / FAIL):
    * both files load; both are 3D; shapes match
    * affine, voxel spacing and axis orientation match (nothing is resampled
      or reoriented -- the original geometry is read and reported as-is)
    * image dtype / Hounsfield range plausibility, no NaN/Inf
    * mask dtype, label values {0,1}, foreground size, connected components
    * HU inside the mask is soft-tissue-like (sanity check on alignment)
    * optional: slice-axis length and z-spacing against streamed metadata
    * optional: streamed 2D PNG slice vs the same slice of the NIfTI volume
      (ties the PNG pipeline back to the 3D geometry)

Outputs:
    datasets/IMAGE_MASK_VALIDATION.md
    datasets/manifests/validation_report.json   (merged under key "nifti_3d")
    datasets/validation/<case_id>_overview.png

Scope statement: this validates ONE case. It says nothing about the other
1,017 scans.
"""
import argparse
import datetime
import json
import shutil
import sys
import tempfile
from pathlib import Path

import numpy as np

REPO_ID = "MedOtter/LIDC-IDRI"
DEFAULT_CASE = "LIDC-IDRI-0001_9720603192"
MARKER = "<!-- generated by validate_nifti_case.py -->"


# ----------------------------------------------------------------------------
# helpers
# ----------------------------------------------------------------------------
def dice(a, b):
    a = a.astype(bool)
    b = b.astype(bool)
    s = a.sum() + b.sum()
    if s == 0:
        return float("nan")
    return float(2.0 * np.logical_and(a, b).sum() / s)


def worst(statuses):
    if "FAIL" in statuses:
        return "FAIL"
    if "WARN" in statuses:
        return "WARN"
    return "PASS"


class Results:
    def __init__(self):
        self.rows = []

    def add(self, name, status, detail):
        self.rows.append({"check": name, "status": status, "detail": detail})
        print(f"[{status}] {name}: {detail}")

    def overall(self):
        return worst([r["status"] for r in self.rows if r["status"] in ("PASS", "WARN", "FAIL")])


# ----------------------------------------------------------------------------
# core NIfTI checks
# ----------------------------------------------------------------------------
def run_checks(img_nii, msk_nii, exp_n, exp_dz, res):
    import nibabel as nib
    from scipy import ndimage

    info = {}
    ishape, mshape = tuple(img_nii.shape), tuple(msk_nii.shape)
    info["image_shape"], info["mask_shape"] = list(ishape), list(mshape)

    if len(ishape) == 3 and len(mshape) == 3:
        res.add("3D volumes", "PASS", f"image {ishape}, mask {mshape}")
    else:
        res.add("3D volumes", "FAIL", f"expected 3D, got image {ishape}, mask {mshape}")
        return info, None, None
    if ishape != mshape:
        res.add("Shape match", "FAIL", f"image {ishape} != mask {mshape}")
        return info, None, None
    res.add("Shape match", "PASS", f"{ishape}")

    # ---- geometry (read as stored; never resampled or reoriented) ----
    ia, ma = img_nii.affine, msk_nii.affine
    max_diff = float(np.abs(ia - ma).max())
    if np.allclose(ia, ma, rtol=1e-4, atol=1e-3):
        res.add("Affine match", "PASS", f"max |image-mask| affine difference = {max_diff:.2e}")
    else:
        res.add("Affine match", "FAIL", f"affines differ, max abs diff = {max_diff:.4g}")
    info["image_affine"] = ia.tolist()
    info["mask_affine"] = ma.tolist()

    iz = np.array(img_nii.header.get_zooms()[:3], dtype=float)
    mz = np.array(msk_nii.header.get_zooms()[:3], dtype=float)
    info["image_zooms_mm"], info["mask_zooms_mm"] = iz.tolist(), mz.tolist()
    if not (np.all(np.isfinite(iz)) and np.all(iz > 0)):
        res.add("Voxel spacing", "FAIL", f"invalid image zooms {iz.tolist()}")
    elif np.allclose(iz, mz, rtol=1e-4, atol=1e-4):
        res.add("Voxel spacing", "PASS", f"{np.round(iz, 4).tolist()} mm (image == mask)")
    else:
        res.add("Voxel spacing", "FAIL", f"image {iz.tolist()} vs mask {mz.tolist()}")

    ic = nib.aff2axcodes(ia)
    mc = nib.aff2axcodes(ma)
    info["image_orientation"], info["mask_orientation"] = "".join(ic), "".join(mc)
    if ic == mc:
        res.add("Orientation", "PASS", f"axis codes {''.join(ic)} (image == mask), as stored")
    else:
        res.add("Orientation", "FAIL", f"image {''.join(ic)} vs mask {''.join(mc)}")
    hdr = img_nii.header
    qf, sf = int(hdr["qform_code"]), int(hdr["sform_code"])
    info["image_qform_code"], info["image_sform_code"] = qf, sf
    if qf == 0 and sf == 0:
        res.add("Spatial transform codes", "WARN", "qform_code and sform_code are both 0 (affine may be a placeholder)")
    else:
        res.add("Spatial transform codes", "PASS", f"qform_code={qf}, sform_code={sf}")

    # ---- dtype / scaling ----
    idt = np.dtype(img_nii.header.get_data_dtype())
    mdt = np.dtype(msk_nii.header.get_data_dtype())
    info["image_dtype_on_disk"], info["mask_dtype_on_disk"] = str(idt), str(mdt)
    res.add("Image dtype", "PASS" if idt == np.int16 else "WARN",
            f"on-disk dtype {idt} (README says int16 HU)")
    res.add("Mask dtype", "PASS" if mdt == np.uint8 else "WARN",
            f"on-disk dtype {mdt} (README says uint8)")
    slope, inter = img_nii.header.get_slope_inter()
    if (slope not in (None, 1.0)) or (inter not in (None, 0.0)):
        res.add("Intensity scaling", "WARN", f"header scl_slope={slope}, scl_inter={inter}: values are rescaled on load")
    else:
        res.add("Intensity scaling", "PASS", "no slope/intercept rescaling")

    # ---- load arrays (raw dtype, no float conversion) ----
    iv = np.asarray(img_nii.dataobj)
    mv = np.asarray(msk_nii.dataobj)

    if not np.isfinite(iv).all():
        res.add("Image finite values", "FAIL", "image contains NaN or Inf")
    else:
        res.add("Image finite values", "PASS", "no NaN/Inf")
    imin, imax = float(iv.min()), float(iv.max())
    sub = iv[::4, ::4, ::2]
    p1, p50, p99 = (float(x) for x in np.percentile(sub, [1, 50, 99]))
    info["image_hu"] = {"min": imin, "max": imax, "p1": p1, "median": p50, "p99": p99}
    if imin <= -500 and imax >= 300:
        res.add("Image HU range", "PASS", f"min {imin:.0f}, max {imax:.0f}, p1/median/p99 = {p1:.0f}/{p50:.0f}/{p99:.0f}")
    else:
        res.add("Image HU range", "WARN", f"min {imin:.0f}, max {imax:.0f}: does not look like chest CT in HU (expect air near -1000, bone above 300)")

    uniq = np.unique(mv)
    info["mask_unique_values"] = [float(u) for u in uniq]
    if set(uniq.tolist()) <= {0, 1}:
        res.add("Mask labels", "PASS", f"unique values {uniq.tolist()}")
    else:
        res.add("Mask labels", "FAIL", f"unexpected values {uniq.tolist()[:10]} (expected subset of {{0,1}})")

    fg = int((mv > 0).sum())
    vox_mm3 = float(np.prod(iz))
    info["mask_foreground_voxels"] = fg
    info["voxel_volume_mm3"] = vox_mm3
    if fg == 0:
        res.add("Mask foreground", "WARN",
                "mask is empty (valid only for the 135 scans without segmentation; for training use scans with has_seg=True)")
        return info, iv, mv
    frac = fg / mv.size
    info["mask_foreground_fraction"] = frac
    res.add("Mask foreground", "PASS" if frac < 0.05 else "WARN",
            f"{fg} voxels = {fg * vox_mm3 / 1000.0:.2f} mL, {100 * frac:.4f}% of volume")

    lab, ncomp = ndimage.label(mv > 0)
    sizes = np.bincount(lab.ravel())[1:]
    order = np.argsort(sizes)[::-1]
    comps = [{"voxels": int(sizes[i]), "volume_mm3": float(sizes[i] * vox_mm3)} for i in order[:10]]
    info["mask_components"] = {"count_6conn": int(ncomp), "largest": comps}
    res.add("Mask components", "PASS", f"{ncomp} connected component(s); largest = {comps[0]['volume_mm3']:.1f} mm3")

    inside = iv[mv > 0].astype(np.float32)
    med = float(np.median(inside))
    air_frac = float((inside < -900).mean())
    info["hu_inside_mask"] = {"median": med, "fraction_below_-900": air_frac}
    if -800 <= med <= 300 and air_frac < 0.5:
        res.add("HU inside mask", "PASS", f"median {med:.0f} HU, {100 * air_frac:.1f}% air-like voxels (nodule-like tissue)")
    else:
        res.add("HU inside mask", "WARN", f"median {med:.0f} HU, {100 * air_frac:.1f}% below -900 HU: mask may be misaligned with anatomy")

    # ---- slice axis / metadata cross-check ----
    codes = ic
    z_axes = [i for i, c in enumerate(codes) if c in ("S", "I")]
    z_axis = z_axes[0] if z_axes else 2
    info["z_axis_from_affine"] = int(z_axis)
    if exp_n is not None:
        match = [i for i, n in enumerate(ishape) if n == exp_n]
        if not match:
            res.add("Slice count vs metadata", "FAIL", f"no axis has length {exp_n} (shape {ishape})")
        else:
            ax = match[0]
            st = "PASS" if ax == z_axis else "WARN"
            res.add("Slice count vs metadata", st, f"axis {ax} has length {exp_n}; affine says z axis is {z_axis} ({codes[z_axis]})")
            if exp_dz is not None:
                dz = float(iz[ax])
                res.add("z spacing vs metadata", "PASS" if abs(dz - exp_dz) < 0.01 else "WARN",
                        f"zoom on axis {ax} = {dz:.4f} mm, metadata spacing_z = {exp_dz}")
    return info, iv, mv


# ----------------------------------------------------------------------------
# optional: tie the streamed 2D PNG back to the 3D volume
# ----------------------------------------------------------------------------
def crosscheck_png(case_id, iv, mv, z_axis, res, max_rows=200):
    try:
        from datasets import load_dataset
        ds = load_dataset(REPO_ID, split="train", streaming=True)
        row = None
        for i, r in enumerate(ds):
            if r["case_id"] == case_id:
                row = r
                break
            if i >= max_rows:
                break
        if row is None:
            res.add("PNG cross-check", "WARN", f"case not found in first {max_rows} streamed rows")
            return None
        png_m = np.asarray(row["mask"])
        png_i = np.asarray(row["image"]).astype(np.float32)
        idx, n = int(row["slice_index"]), int(row["n_slices"])
    except Exception as e:  # network / decode problems must not hide the 3D result
        res.add("PNG cross-check", "WARN", f"could not stream PNG sample: {type(e).__name__}: {e}")
        return None

    png_fg = png_m > 0
    if png_fg.sum() == 0:
        res.add("PNG cross-check", "WARN", "streamed mask slice is empty: cannot compare")
        return None
    best = None
    for si in sorted({idx, n - 1 - idx}):
        if si < 0 or si >= iv.shape[z_axis]:
            continue
        vm = np.take(mv, si, axis=z_axis)
        vi = np.take(iv, si, axis=z_axis).astype(np.float32)
        for k in range(4):
            for flip in (False, True):
                t = np.rot90(vm, k)
                ti = np.rot90(vi, k)
                if flip:
                    t, ti = np.fliplr(t), np.fliplr(ti)
                if t.shape != png_fg.shape:
                    continue
                d = dice(t > 0, png_fg)
                if best is None or d > best["dice"]:
                    c = float(np.corrcoef(np.clip(ti, -1100, 600).ravel(), png_i.ravel())[0, 1])
                    best = {"dice": d, "slice_index_used": si, "rot90_k": k, "fliplr": flip, "image_corr": c}
    if best is None:
        res.add("PNG cross-check", "WARN", "no shape-compatible transform between PNG and NIfTI slice")
        return None
    d = best["dice"]
    st = "PASS" if d >= 0.95 else ("WARN" if d >= 0.5 else "FAIL")
    res.add("PNG cross-check", st,
            f"streamed slice_index={idx}/{n} best matches NIfTI slice {best['slice_index_used']} "
            f"(rot90 k={best['rot90_k']}, fliplr={best['fliplr']}): mask Dice={d:.3f}, "
            f"image Pearson r={best['image_corr']:.3f}; PNG mask values={np.unique(png_m).tolist()}")
    return best


